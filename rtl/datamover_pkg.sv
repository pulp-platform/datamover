package datamover_pkg;

  typedef struct packed {
    hci_package::hci_streamer_ctrl_t data_in_source_ctrl;
    hci_package::hci_streamer_ctrl_t data_out_sink_ctrl;
  } ctrl_streamer_t;
  typedef struct packed {
    hci_package::hci_streamer_flags_t data_in_source_flags;
    hci_package::hci_streamer_flags_t data_out_sink_flags;
    logic tcdm_fifo_empty;
  } flags_streamer_t;

  parameter int unsigned MaxBandwidth = 512; // support maximum 512bits of bandwidth

  // Defaults of the top-level parameters
  parameter int unsigned AddrWidth          = 32;
  parameter int unsigned IdWidth            = 10;
  parameter int unsigned Bandwidth          = 576;
  parameter int unsigned ElemsPerWord       = 8;
  parameter int unsigned ElemWidth          = 8;
  parameter int unsigned NumCores           = 8;
  parameter int unsigned NumContext         = 2;
  parameter int unsigned MisalignedAccesses = 1;

  // Widths of the job-dependent register fields generated by RDL
  parameter int unsigned TensorSizeWidth =
    $bits(datamover_regif_pkg::datamover_regif__dm_matrix_dim__tensor_size_m__out_t);
  parameter int unsigned TotalElemWidth =
    $bits(datamover_regif_pkg::datamover_regif__dm_channels__total_elements__out_t);
  parameter int unsigned NumChannelsWidth =
    $bits(datamover_regif_pkg::datamover_regif__dm_channels__num_channels__out_t);
  parameter int unsigned ConvStrideWidth =
    $bits(datamover_regif_pkg::datamover_regif__dm_ctrl_engine__conv_stride__out_t);
  parameter int unsigned Im2colLog2wWidth =
    $bits(datamover_regif_pkg::datamover_regif__dm_ctrl_engine__im2col_log2w__out_t);
    parameter int unsigned Im2colKernelWidth =
      $bits(datamover_regif_pkg::datamover_regif__dm_ctrl_engine__im2col_kernel__out_t);

  // The im2col unit is instantiated when EnableIm2col is set on datamover_top.
  parameter bit          EnableIm2col       = 1'b1;
  // The element buffer is instantiated when EnableBuffer is set: transpose, unfold, and fold need it.
  parameter bit          EnableBuffer       = 1'b1;
  // The im2col unit supports kernels up to Im2colKernel (3 or 5) and rows from 2**Im2colMinLog2W pixels.
  parameter int unsigned Im2colKernel       = 3;
  parameter int unsigned Im2colMinLog2W     = 3;
  parameter int unsigned FifoDepth          = 2;
  // Element-granularity transpose steps by 1, 2 or 4 elements
  parameter int unsigned MaxTranspStride     = 4;
  parameter int unsigned TranspStrideWidth   = $clog2(MaxTranspStride) + 1;
  // transp_len counts up to NumElems = BandwidthAligned/ElemWidth inclusive.
  parameter int unsigned TranspLenWidth      = $clog2(MaxBandwidth/8) + 1;

  typedef enum logic[1:0] { TRANSP_NONE, TRANSP_1ELEM, TRANSP_2ELEM, TRANSP_4ELEM } transp_mode_e;
  typedef enum logic[4:0] {
    DATAMOVER_COPY, DATAMOVER_TRANSPOSE, DATAMOVER_BLOCK_LAYOUT, DATAMOVER_BLOCK_TRANSPOSE,
    DATAMOVER_UNFOLD, DATAMOVER_FOLD, DATAMOVER_IM2COL
  } datamover_mode_e;
  typedef struct packed {
    transp_mode_e                     transp_mode;
    logic [TranspLenWidth-1:0]      transp_len;
    logic [TranspStrideWidth-1:0]   transp_stride;  // 1, 2, or 4 elements
    logic [ConvStrideWidth-1:0]     conv_stride;    // im2col column subsample, 1 or 2
    logic                             im2col_pack;    // im2col: run the im2col unit
    logic [Im2colLog2wWidth-1:0]    im2col_log2w;   // im2col unit: log2 of the image row width
    logic [Im2colKernelWidth-1:0]    im2col_kernel;  // im2col unit: kernel side, 3 or 5
    datamover_mode_e                  datamover_mode;
    logic [TensorSizeWidth-1:0]     tensor_size_m;
    logic [TensorSizeWidth-1:0]     tensor_size_n;
    logic [TotalElemWidth-1:0]      total_elements; // num_channels * size_m * size_n (from HAL)
    logic [NumChannelsWidth-1:0]    num_channels;   // number of channels (for unfolding/folding)
  } ctrl_engine_t;

  // Datamover job FSM states
  typedef enum logic [1:0] { DM_IDLE, DM_STARTING, DM_WORKING, DM_FINISHED } datamover_state_e;

endpackage
