package datamover_pkg;

  typedef struct packed {
    hci_package::hci_streamer_ctrl_t data_in_source_ctrl;
    hci_package::hci_streamer_ctrl_t data_out_sink_ctrl;
  } ctrl_streamer_t;
  typedef struct packed {
    hci_package::hci_streamer_flags_t data_in_source_flags;
    hci_package::hci_streamer_flags_t data_out_sink_flags;
    logic tcdm_fifo_empty;
  } flags_streamer_t;

  localparam int unsigned ByteWidth    = 8;
  localparam int unsigned MaxBandwidth = 512; // support maximum 512bits of bandwidth

  // Defaults of the top-level parameters
  localparam int unsigned AddrWidth          = 32;
  localparam int unsigned IdWidth            = 10;
  localparam int unsigned Bandwidth          = 576;
  localparam int unsigned ElemsPerWord       = 8;
  localparam int unsigned ElemWidth          = 8;
  localparam int unsigned NumCores           = 8;
  localparam int unsigned NumContext         = 2;
  localparam int unsigned MisalignedAccesses = 1;

  // Widths of the job-dependent register fields generated by RDL
  localparam int unsigned TensorSizeWidth =
    $bits(datamover_regif_pkg::datamover_regif__dm_matrix_dim__tensor_size_m__out_t);
  localparam int unsigned TotalElemWidth =
    $bits(datamover_regif_pkg::datamover_regif__dm_channels__total_elements__out_t);
  localparam int unsigned NumChannelsWidth =
    $bits(datamover_regif_pkg::datamover_regif__dm_channels__num_channels__out_t);
  localparam int unsigned ConvStrideWidth =
    $bits(datamover_regif_pkg::datamover_regif__dm_ctrl_engine__conv_stride__out_t);
  localparam int unsigned Im2colLog2wWidth =
    $bits(datamover_regif_pkg::datamover_regif__dm_ctrl_engine__im2col_log2w__out_t);
  localparam int unsigned Im2colKernelWidth =
    $bits(datamover_regif_pkg::datamover_regif__dm_ctrl_engine__im2col_kernel__out_t);
  localparam int unsigned PadKernelWidth =
    $bits(datamover_regif_pkg::datamover_regif__dm_im2col_pad__kernel_h__out_t);
  localparam int unsigned PadWidth =
    $bits(datamover_regif_pkg::datamover_regif__dm_im2col_pad__pad_top__out_t);
  localparam int unsigned PadShiftWidth =
    $bits(datamover_regif_pkg::datamover_regif__dm_im2col_pad__shift__out_t);
  localparam int unsigned PadRightWidth =
    $bits(datamover_regif_pkg::datamover_regif__dm_im2col_pad__pad_right__out_t);

  // The im2col hardware is instantiated when EnableIm2col is set on datamover_top: the im2col unit, the
  // zero border, and the stride-2 merge. im2row (ROW_BLOCK) needs none of it.
  localparam bit          EnableIm2col       = 1'b1;
  // The element buffer is instantiated when EnableBuffer is set: transpose, unfold, and fold need it.
  localparam bit          EnableBuffer       = 1'b1;
  // The im2col unit supports odd kernels up to Im2colKernel (3 to 7) and rows from 2**Im2colMinLog2W pixels.
  localparam int unsigned Im2colKernel       = 3;
  localparam int unsigned Im2colMinLog2W     = 3;
  localparam int unsigned FifoDepth          = 2;
  // Element-granularity transpose steps by 1, 2 or 4 elements
  localparam int unsigned MaxTranspStride     = 4;
  localparam int unsigned TranspStrideWidth   = $clog2(MaxTranspStride) + 1;
  // transp_len counts up to NumElems = BandwidthAligned/ElemWidth inclusive.
  localparam int unsigned TranspLenWidth      = $clog2(MaxBandwidth / ByteWidth) + 1;

  typedef enum logic[1:0] { TRANSP_NONE, TRANSP_1ELEM, TRANSP_2ELEM, TRANSP_4ELEM } transp_mode_e;
  typedef enum logic[4:0] {
    DATAMOVER_COPY, DATAMOVER_TRANSPOSE, DATAMOVER_BLOCK_LAYOUT, DATAMOVER_BLOCK_TRANSPOSE,
    DATAMOVER_UNFOLD, DATAMOVER_FOLD, DATAMOVER_IM2COL
  } datamover_mode_e;
  typedef struct packed {
    transp_mode_e                     transp_mode;
    logic [TranspLenWidth-1:0]      transp_len;
    logic [TranspStrideWidth-1:0]   transp_stride;  // 1, 2, or 4 elements
    logic [ConvStrideWidth-1:0]     conv_stride;    // im2col column subsample, 1 or 2
    logic                             im2col_pack;    // im2col: run the im2col unit
    logic [Im2colLog2wWidth-1:0]    im2col_log2w;   // im2col unit: log2 of the image row width
    logic [Im2colKernelWidth-1:0]    im2col_kernel;  // im2col unit: kernel side, odd, 3 to Im2colKernel
    logic [PadKernelWidth-1:0]       pad_kernel_h;   // row-major im2col: kernel height
    logic [PadKernelWidth-1:0]       pad_kernel_w;   // row-major im2col: kernel width
    logic [PadWidth-1:0]             pad_top;        // row-major im2col: zero rows above the image
    logic [PadWidth-1:0]             pad_bottom;     // row-major im2col: zero rows below the image
    logic [PadWidth-1:0]             pad_left;       // row-major im2col: zero columns left of the image
    logic [PadRightWidth-1:0]        pad_right;      // row-major im2col: lanes of the last beat past the image
    logic [PadShiftWidth-1:0]        pad_shift;      // row-major im2col: start offset in the first aligned word
    datamover_mode_e                  datamover_mode;
    logic [TensorSizeWidth-1:0]     tensor_size_m;
    logic [TensorSizeWidth-1:0]     tensor_size_n;
    logic [TotalElemWidth-1:0]      total_elements; // num_channels * size_m * size_n (from HAL)
    logic [31:0]                    out_tot_len;    // output beats of the job, the sink length
    logic [NumChannelsWidth-1:0]    num_channels;   // number of channels (for unfolding/folding)
  } ctrl_engine_t;

  // Datamover job FSM states
  typedef enum logic [1:0] { DM_IDLE, DM_STARTING, DM_WORKING, DM_FINISHED } datamover_state_e;

endpackage
